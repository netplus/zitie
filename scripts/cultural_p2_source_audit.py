#!/usr/bin/env python3
"""P2: fail-closed secondary-dictionary evidence inventory (NOT approval).

This intentionally does not scrape provider sites during CI; externally verified
links are frozen evidence locators, NOT releases of mainland pronunciations.
All source links must be visited in an editorial review before publication.
"""
from __future__ import annotations
import argparse,copy,json,re,unicodedata
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlsplit,parse_qs

ROOT=Path(__file__).resolve().parents[1]
FIRST=ROOT/'data/cultural_edition/first_batch_draft.json'
P4=ROOT/'data/cultural_edition/p4_multipage_prototypes.json'
EVIDENCE=ROOT/'data/cultural_edition/p2_direct_lexicon_evidence_20261024.json'
DOC_REGEX=re.compile(r'^/dictView\.jsp$')
DIRECT_HOSTS={'dict.concised.moe.edu.tw','dict.revised.moe.edu.tw'}

def nfc(s:str)->str:
    return ' '.join(unicodedata.normalize('NFC',s).strip().split())

def validate(first:dict,p4:dict,evidence:dict)->dict:
    if first.get('review_state')!='editorial_draft_not_for_release':
        raise ValueError('First manuscript must remain unreviewed')
    if p4.get('review_state')!='editorial_draft_not_for_release':
        raise ValueError('P4 manuscript must remain unreviewed')
    if evidence.get('canonical_mainland_review_complete') is not False:
        raise ValueError('Secondary evidence cannot authorize mainland publication')
    if evidence.get('source_jurisdiction')!='Taiwan':
        raise ValueError('Evidence must disclose Taiwanese jurisdiction')
    if evidence.get('target_publication_jurisdiction')!='Chinese mainland':
        raise ValueError('Target jurisdiction must be explicit')
    slots=defaultdict(list)
    for manuscript in (first,p4):
        for entry in manuscript['entries']:
            for term in entry['terms']:
                if term.get('status') not in ('review_pending','blocked'):
                    raise ValueError('Unreviewed manuscript term auto-promoted: '+term['word'])
                if 'word' not in term or 'pinyin' not in term or not nfc(term['pinyin']):
                    raise ValueError('Candidate term incomplete')
                slots[nfc(term['word'])].append({
                    'character':entry['character'],
                    'draft_pinyin':nfc(term['pinyin']),
                    'original_status':term['status']})
    if sum(map(len,slots.values()))!=36:
        raise ValueError('First 4 and P4 sample must contain exactly 36 term placements')
    verified={}
    glyph_evidence=[]
    for item in evidence['entries']:
        for attr in ('word','source_headword','source_pinyin','source_url',
                     'sense_key','evidence_kind','comparison_to_current_sample'):
            if not isinstance(item.get(attr),str) or not item[attr].strip():
                raise ValueError('Evidence field absent: '+attr)
        url=urlsplit(item['source_url'])
        if url.scheme!='https' or url.hostname not in DIRECT_HOSTS or not DOC_REGEX.fullmatch(url.path):
            raise ValueError('Unsupported source URL: '+item['source_url'])
        args=parse_qs(url.query)
        if not re.fullmatch(r'\d{1,8}',args.get('ID',[''])[0]):
            raise ValueError('Missing original dictionary record ID')
        if item['source_organization']!='Taiwan Ministry of Education':
            raise ValueError('Source authority was misidentified')
        if item['pronunciation_status']!='cross_region_reference_only' or item['reviewed_by'] is not None:
            raise ValueError('Unapproved direct sources cannot become normative by implication')
        word=nfc(item['word'])
        if item['evidence_kind']=='external_character_entry':
            if word!='龠' or item['comparison_to_current_sample']!='original_pdf_does_not_have_adopted_pinyin':
                raise ValueError('A character-only link cannot be used as a word-level direct match')
            glyph_evidence.append(item)
            continue
        if item['evidence_kind']!='direct_word_entry' or word not in slots:
            raise ValueError('Word direct source does not match the manuscript: '+word)
        if word in verified:
            raise ValueError('Duplicate direct dictionary headword: '+word)
        # A Chinese simplified/traditional headword pair is explicitly recorded
        # by the editor; no lossy autogenerated simplified conversion is done.
        if item['sheet_characters']!=[s['character'] for s in slots[word]]:
            raise ValueError('Source scope must match all occurrences of '+word)
        observed=nfc(item['source_pinyin'])
        variants={s['draft_pinyin'] for s in slots[word]}
        if len(variants)!=1:
            raise ValueError('One candidate term is inconsistent between pages')
        candidate=next(iter(variants))
        difference=(candidate!=observed)
        expected_flag='disagrees_with_draft_neutral_tone' if difference else 'aligned'
        if item['comparison_to_current_sample']!=expected_flag:
            raise ValueError('Pinyin discrepancy improperly labeled for '+word)
        verified[word]=item
    if len(glyph_evidence)!=1:
        raise ValueError('龠 reading remains separately quarantined')
    rows=[]
    for word,occurrences in slots.items():
        source=verified.get(word)
        conflict=source is not None and nfc(source['source_pinyin'])!=occurrences[0]['draft_pinyin']
        rows.append({
          'word':word,'used_by':[i['character'] for i in occurrences],
          'draft_pinyin':occurrences[0]['draft_pinyin'],
          'secondary_dictionary_pinyin':source['source_pinyin'] if source else None,
          'secondary_direct_entry':bool(source),
          'evidence_url':source['source_url'] if source else None,
          'tone_or_reading_conflict':conflict,
          'editorial_action':('resolve_cross_region_conflict' if conflict
                              else 'find_mainland_dictionary_and_editor_signoff' if source
                              else 'find_direct_entry_and_mainland_dictionary'),
          'release_eligible':False
        })
    rows.sort(key=lambda item:(item['used_by'][0],item['word']))
    counts={
      'manuscript_word_placements':sum(map(len,slots.values())),
      'unique_candidate_words':len(slots),
      'unique_words_with_secondary_direct_entry':len(verified),
      'unique_words_without_direct_entry':len(slots)-len(verified),
      'candidate_conflicts':sum(x['tone_or_reading_conflict'] for x in rows),
      'additional_char_entry_not_promoted':len(glyph_evidence)
    }
    # Gates explicitly bind to this milestone's reviewed, frozen source list.
    if counts!={'manuscript_word_placements':36,
                 'unique_candidate_words':35,
                 'unique_words_with_secondary_direct_entry':19,
                 'unique_words_without_direct_entry':16,
                 'candidate_conflicts':1,
                 'additional_char_entry_not_promoted':1}:
        raise ValueError('Review coverage changed; audit counts explicitly before accepting')
    if not any(x['word']=='月亮' and x['tone_or_reading_conflict'] for x in rows):
        raise ValueError('Known month/mōon/neutral-tone difference was dropped')
    return {
      'result':'SECONDARY_CROSSCHECK_ONLY_NOT_RELEASE',
      'official_mainland_word_pronunciations_approved':0,
      'source_jurisdiction':'Taiwan; target China mainland',
      'counts':counts,
      'words':rows,
      'unpromoted_character_only':[{'character':x['word'],
         'proposed_pinyin':x['source_pinyin'],'source_url':x['source_url'],
         'reason':'Original PDF does not show adopted pinyin'} for x in glyph_evidence],
      'note':'Static source link inventory checked manually; CI does not fetch/endorse any dictionary page. Every item awaits applicable mainland standards and editorial review.'
    }

def audit(first=FIRST,p4=P4,evidence=EVIDENCE):
    return validate(*[json.loads(p.read_text(encoding='utf-8')) for p in (first,p4,evidence)])

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--first',type=Path,default=FIRST)
    p.add_argument('--p4',type=Path,default=P4)
    p.add_argument('--evidence',type=Path,default=EVIDENCE)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    result=audit(args.first,args.p4,args.evidence)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print(json.dumps({'result':result['result'],'counts':result['counts'],
       'conflicts':[x for x in result['words'] if x['tone_or_reading_conflict']]},ensure_ascii=False,indent=2))

if __name__=='__main__':
    main()
